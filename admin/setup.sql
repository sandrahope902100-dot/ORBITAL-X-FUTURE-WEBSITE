-- ORBITAL X FUTURE founder dashboard setup
-- Before using the dashboard:
-- 1) In Supabase Authentication settings, disable public sign-ups.
-- 2) Create/invite only the founder account: orbitalxfuture@gmail.com.
-- 3) Run this complete SQL script in Supabase SQL Editor.
-- 4) Never expose a service_role or secret key in the website.

create table if not exists public.founder_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 100),
  body text not null check (char_length(body) between 1 and 5000),
  created_at timestamptz not null default now()
);

alter table public.founder_notes enable row level security;

drop policy if exists "Founder can read own notes" on public.founder_notes;
create policy "Founder can read own notes"
on public.founder_notes for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Founder can create own notes" on public.founder_notes;
create policy "Founder can create own notes"
on public.founder_notes for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Founder can update own notes" on public.founder_notes;
create policy "Founder can update own notes"
on public.founder_notes for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Founder can delete own notes" on public.founder_notes;
create policy "Founder can delete own notes"
on public.founder_notes for delete
to authenticated
using (auth.uid() = user_id);

grant select, insert, update, delete on public.founder_notes to authenticated;
grant usage, select on sequence public.founder_notes_id_seq to authenticated;